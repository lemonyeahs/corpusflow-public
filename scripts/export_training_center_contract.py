"""Generate M0 design artifacts (not live routes). --check detects stale artifacts."""

import argparse
import json
from pathlib import Path
from typing import Any

from corpusflow.contracts.training_center import models as m
from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parents[1]
REF = "#/components/schemas/"
ALIASES = {
    "Catalog": m.Catalog,
    "TrainingKind": m.TrainingKind,
    "Split": m.Split,
    "FileFormat": m.FileFormat,
    "SourceKind": m.SourceKind,
    "ObjectType": m.ObjectType,
    "ProcessingStatus": m.ProcessingStatus,
    "Sample": m.Sample,
    "Unit": m.Unit,
}
ROUTES = {
    "/training-center/overview": "OverviewResponse",
    "/training-center/formats/{format}/stats": "FormatStatsResponse",
    "/training-center/files": "FilesResponse",
    "/training-center/files/{file_id}": "FileDetailResponse",
    "/training-center/datasets/{dataset_id}/manifest": "ManifestResponse",
    "/training-center/datasets": "DatasetsResponse",
    "/training-center/datasets/{dataset_id}/overview": "DatasetOverviewResponse",
    "/training-center/datasets/{dataset_id}/samples": "SamplesResponse",
    "/pipeline-runs/{run_id}/summary": "ProcessingSummaryResponse",
    "/pipeline-runs/{run_id}/steps/{step_id}/comparison": "ComparisonResponse",
    "/training-center/files/{file_id}/comparison": "ComparisonResponse",
    "/lineage/graph": "LineageGraph",
}


def typescript(schema: dict[str, Any]) -> str:
    """Render only constructs emitted by our models; fail on unsupported constructs."""
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(typescript(part) for part in schema[union])
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return str(kind)
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            fields = [
                f"{json.dumps(key)}{'' if key in required else '?'}: {typescript(value)}"
                for key, value in schema["properties"].items()
            ]
            return "{ " + "; ".join(fields) + " }"
        additional = schema.get("additionalProperties", {})
        return (
            "Record<string, "
            + (typescript(additional) if isinstance(additional, dict) else "unknown")
            + ">"
        )
    if not schema or set(schema) <= {"title", "description"}:
        return "unknown"
    raise ValueError(f"Unsupported TypeScript schema: {schema}")


def artifacts() -> dict[Path, str]:
    schemas = {}
    for name, model in {**m.RESPONSES, **m.QUERIES, **ALIASES}.items():
        schema = TypeAdapter(model).json_schema(ref_template=REF + "{model}")
        schemas.update(schema.pop("$defs", {}))
        schemas[name] = schema
    ts = "/** Generated by scripts/export_training_center_contract.py. Do not edit. */\n"
    ts += f"export const CONTRACT_VERSION = {json.dumps(m.CONTRACT_VERSION)} as const;\n"
    ts += (
        "\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    paths = {}
    for path, model_name in ROUTES.items():
        parameters = [
            {"name": p[1:-1], "in": "path", "required": True, "schema": {"type": "string"}}
            for p in path.split("/")
            if p.startswith("{")
        ]
        parameters.append(
            {
                "name": "X-Workspace-ID",
                "in": "header",
                "required": True,
                "schema": {"type": "string"},
            }
        )
        query_name = {
            "FilesResponse": "FilesQuery",
            "SamplesResponse": "SamplesQuery",
            "FormatStatsResponse": "StatsQuery",
            "LineageGraph": "GraphQuery",
            "DatasetOverviewResponse": "DatasetQuery",
            "DatasetsResponse": "DatasetsQuery",
            "ManifestResponse": "DatasetQuery",
            "ComparisonResponse": "ComparisonQuery",
        }.get(model_name, "CatalogQuery")
        if path.startswith("/pipeline-runs/"):
            query_name = (
                "ProcessingComparisonQuery"
                if model_name == "ComparisonResponse"
                else "ProcessingQuery"
            )
        query = schemas[query_name]
        for name, schema in query["properties"].items():
            parameters.append(
                {
                    "name": name,
                    "in": "query",
                    "schema": schema,
                    "required": name in query.get("required", []),
                }
            )

        def response(name):
            return {
                "description": name,
                "content": {"application/json": {"schema": {"$ref": REF + name}}},
            }

        paths["/api/v1" + path] = {
            "get": {
                "operationId": "design_"
                + path.strip("/").replace("/", "_").replace("{", "").replace("}", ""),
                "x-implementation-status": "planned",
                "parameters": parameters,
                "security": [{"BearerAuth": []}],
                "responses": {
                    "200": response(model_name),
                    **{str(code): response("ApiErrorBody") for code in (401, 403, 404, 409, 422)},
                },
            }
        }
    for path, query_name in (
        ("/training-center/datasets/{dataset_id}/export", "ExportQuery"),
        ("/pipeline-runs/{run_id}/export", "ProcessingExportQuery"),
    ):
        parameters = [
            {"name": p[1:-1], "in": "path", "required": True, "schema": {"type": "string"}}
            for p in path.split("/")
            if p.startswith("{")
        ]
        parameters.append(
            {
                "name": "X-Workspace-ID",
                "in": "header",
                "required": True,
                "schema": {"type": "string"},
            }
        )
        query = schemas[query_name]
        parameters += [
            {
                "name": name,
                "in": "query",
                "schema": schema,
                "required": name in query.get("required", []),
            }
            for name, schema in query["properties"].items()
        ]
        paths["/api/v1" + path] = {
            "get": {
                "x-implementation-status": "planned",
                "security": [{"BearerAuth": []}],
                "parameters": parameters,
                "responses": {
                    "200": {
                        "description": "Complete filtered UTF-8 export; capped before headers",
                        "headers": {
                            "Content-Disposition": {"required": True, "schema": {"type": "string"}}
                        },
                        "content": {
                            mime: {"schema": {"type": "string", "format": "binary"}}
                            for mime in (
                                "application/x-ndjson",
                                "text/markdown",
                                "text/csv",
                                "text/plain",
                            )
                        },
                    },
                    **{
                        str(code): response("ApiErrorBody")
                        for code in (401, 403, 404, 409, 413, 422)
                    },
                },
            }
        }
    document = {
        "openapi": "3.1.0",
        "info": {
            "title": "Training Center M0 design contract — NOT the live API",
            "version": m.CONTRACT_VERSION,
            "description": "Planned JSON response contracts. Live routes: docs/api/openapi.json. "
            "Binary exports, manifest and detail handoffs are specified in the v1 spec.",
        },
        "paths": paths,
        "components": {
            "schemas": schemas,
            "securitySchemes": {"BearerAuth": {"type": "http", "scheme": "bearer"}},
        },
    }
    return {
        ROOT / "apps/web/src/contracts/training-center.generated.ts": ts,
        ROOT / "docs/api/training-center.openapi.json": json.dumps(
            document, ensure_ascii=False, indent=2
        )
        + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale contract artifacts: " + ", ".join(stale))
    print("Training Center contract artifacts: PASS")


if __name__ == "__main__":
    main()
